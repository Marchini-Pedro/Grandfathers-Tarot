-- the settings of one card (its key: "wave_small", "custom_7"): { setting = value }, built once
local by_card = nil

UserDefaults.card = function (key)
	if not by_card then
		by_card = {}

		for setting, value in pairs(UserDefaults.cards) do
			for _, prefix in ipairs(UserDefaults.CARD_PREFIXES) do
				if setting:sub(1, #prefix) == prefix then
					local card = setting:sub(#prefix + 1)

					by_card[card] = by_card[card] or {}
					by_card[card][setting] = value

					break
				end
			end
		end
	end

	return by_card[key] or {}
end

return UserDefaults
